/* 向ST7735发送一条命令。 */
static void lcd_command(uint8_t command)
{
    if (s_spi_error != ESP_OK) return;
    gpio_set_level(TFT_DC_PIN, 0);
    spi_transaction_t transaction = {.length = 8, .tx_buffer = &command};
    s_spi_error = spi_device_polling_transmit(s_lcd, &transaction);
}

/* 向ST7735发送命令参数。 */
static void lcd_data(const void *data, size_t length)
{
    if (length == 0 || s_spi_error != ESP_OK) return;
    gpio_set_level(TFT_DC_PIN, 1);
    spi_transaction_t transaction = {.length = length * 8, .tx_buffer = data};
    s_spi_error = spi_device_polling_transmit(s_lcd, &transaction);
}

/* 发送带参数的ST7735初始化命令。 */
static void lcd_command_data(uint8_t command, const uint8_t *data, size_t length)
{
    lcd_command(command);
    lcd_data(data, length);
}

/* 初始化与Arduino版INITR_BLACKTAB等效的ST7735横屏模式。 */
static void lcd_panel_init(void)
{
    gpio_set_level(TFT_RST_PIN, 0);
    esp_rom_delay_us(20000);
    gpio_set_level(TFT_RST_PIN, 1);
    vTaskDelay(pdMS_TO_TICKS(150));

    lcd_command(0x01);
    vTaskDelay(pdMS_TO_TICKS(150));
    lcd_command(0x11);
    vTaskDelay(pdMS_TO_TICKS(500));
    const uint8_t frame_rate[] = {0x01, 0x2C, 0x2D};
    const uint8_t frame_rate3[] = {0x01, 0x2C, 0x2D, 0x01, 0x2C, 0x2D};
    const uint8_t power1[] = {0xA2, 0x02, 0x84};
    const uint8_t power3[] = {0x0A, 0x00};
    const uint8_t power4[] = {0x8A, 0x2A};
    const uint8_t power5[] = {0x8A, 0xEE};
    lcd_command_data(0xB1, frame_rate, sizeof(frame_rate));
    lcd_command_data(0xB2, frame_rate, sizeof(frame_rate));
    lcd_command_data(0xB3, frame_rate3, sizeof(frame_rate3));
    const uint8_t inversion = 0x07;
    lcd_command_data(0xB4, &inversion, 1);
    lcd_command_data(0xC0, power1, sizeof(power1));
    const uint8_t power2 = 0xC5;
    lcd_command_data(0xC1, &power2, 1);
    lcd_command_data(0xC2, power3, sizeof(power3));
    lcd_command_data(0xC3, power4, sizeof(power4));
    lcd_command_data(0xC4, power5, sizeof(power5));
    const uint8_t vcom = 0x0E;
    lcd_command_data(0xC5, &vcom, 1);
    const uint8_t color_mode = 0x05;
    const uint8_t portrait_direction = 0xC8;
    const uint8_t portrait_columns[] = {0x00, 0x00, 0x00, 0x7F};
    const uint8_t portrait_rows[] = {0x00, 0x00, 0x00, 0x9F};
    lcd_command_data(0x36, &portrait_direction, 1);
    lcd_command_data(0x3A, &color_mode, 1);
    lcd_command_data(0x2A, portrait_columns, sizeof(portrait_columns));
    lcd_command_data(0x2B, portrait_rows, sizeof(portrait_rows));
    const uint8_t gamma_positive[] = {
        0x02,0x1C,0x07,0x12,0x37,0x32,0x29,0x2D,
        0x29,0x25,0x2B,0x39,0x00,0x01,0x03,0x10,
    };
    const uint8_t gamma_negative[] = {
        0x03,0x1D,0x07,0x06,0x2E,0x2C,0x29,0x2D,
        0x2E,0x2E,0x37,0x3F,0x00,0x00,0x02,0x10,
    };
    lcd_command_data(0xE0, gamma_positive, sizeof(gamma_positive));
    lcd_command_data(0xE1, gamma_negative, sizeof(gamma_negative));

    /* INITR_BLACKTAB在公共初始化后切换为RGB颜色顺序。 */
    const uint8_t black_tab_direction = 0xC0;
    lcd_command_data(0x36, &black_tab_direction, 1);
    lcd_command(0x13);
    vTaskDelay(pdMS_TO_TICKS(10));
    lcd_command(0x29);
    vTaskDelay(pdMS_TO_TICKS(100));

    /* 与Adafruit setRotation(1)完全相同：MY | MV | RGB。 */
    /* 按小车上显示屏的实际安装方向，将横屏画面旋转 180 度。 */
    const uint8_t landscape_direction = 0xA0;
    lcd_command_data(0x36, &landscape_direction, 1);
}

/* 将RGB565颜色转换成屏幕SPI传输所需的高字节在前格式。 */
static uint16_t lcd_color(uint16_t color)
{
    return (uint16_t)((color << 8) | (color >> 8));
}

/* 在内存画布中填充矩形。 */
static void fill_rect(int x, int y, int width, int height, uint16_t color)
{
    if (x < 0 || y < 0 || x + width > TFT_WIDTH || y + height > TFT_HEIGHT) return;
    uint16_t output_color = lcd_color(color);
    for (int row = y; row < y + height; row++) {
        for (int column = x; column < x + width; column++) {
            s_framebuffer[row * TFT_WIDTH + column] = output_color;
        }
    }
}

/* 绘制一个24x24中文点阵字。 */
static void draw_hanzi(int x, int y, int index, uint16_t color)
{
    for (int row = 0; row < 24; row++) {
        for (int column = 0; column < 24; column++) {
            uint8_t byte = s_hanzi[index][row * 3 + column / 8];
            if (byte & (0x80 >> (column & 7))) fill_rect(x + column, y + row, 1, 1, color);
        }
    }
}

/* 用放大的线段绘制一个数字。 */
static void draw_digit(int x, int y, int digit, uint16_t color)
{
    static const uint8_t segments[10] = {
        0x3F, 0x06, 0x5B, 0x4F, 0x66, 0x6D, 0x7D, 0x07, 0x7F, 0x6F,
    };
    uint8_t mask = segments[digit];
    if (mask & 0x01) fill_rect(x + 3, y, 8, 3, color);
    if (mask & 0x02) fill_rect(x + 11, y + 3, 3, 7, color);
    if (mask & 0x04) fill_rect(x + 11, y + 12, 3, 7, color);
    if (mask & 0x08) fill_rect(x + 3, y + 19, 8, 3, color);
    if (mask & 0x10) fill_rect(x, y + 12, 3, 7, color);
    if (mask & 0x20) fill_rect(x, y + 3, 3, 7, color);
    if (mask & 0x40) fill_rect(x + 3, y + 9, 8, 3, color);
}

/* 绘制A、B、D轮名称。 */
static void draw_wheel_letter(int x, int y, char letter, uint16_t color)
{
    if (letter == 'A') {
        fill_rect(x, y + 5, 3, 17, color); fill_rect(x + 12, y + 5, 3, 17, color);
        fill_rect(x + 3, y + 2, 9, 3, color); fill_rect(x + 3, y + 11, 9, 3, color);
    } else if (letter == 'B') {
        fill_rect(x, y + 2, 3, 20, color); fill_rect(x + 3, y + 2, 8, 3, color);
        fill_rect(x + 3, y + 10, 8, 3, color); fill_rect(x + 3, y + 19, 8, 3, color);
        fill_rect(x + 11, y + 5, 3, 5, color); fill_rect(x + 11, y + 13, 3, 6, color);
    } else {
        fill_rect(x, y + 2, 3, 20, color); fill_rect(x + 3, y + 2, 7, 3, color);
        fill_rect(x + 3, y + 19, 7, 3, color); fill_rect(x + 10, y + 5, 3, 14, color);
    }
}

/* 绘制一个轮子的名称、方向符号和三位PWM。 */
static void draw_wheel_row(int y, char wheel, int pwm, uint16_t color)
{
    draw_wheel_letter(8, y, wheel, color);
    if (pwm < 0) fill_rect(31, y + 10, 12, 3, COLOR_RED);
    else fill_rect(35, y + 5, 3, 13, pwm > 0 ? color : COLOR_WHITE);
    if (pwm > 0) fill_rect(31, y + 10, 11, 3, color);
    int value = abs(pwm);
    draw_digit(53, y, (value / 100) % 10, color);
    draw_digit(72, y, (value / 10) % 10, color);
    draw_digit(91, y, value % 10, color);
}

/* 在顶部居中绘制二到四个大号中文状态字。 */
static void draw_state_word(const uint8_t *characters, int count, uint16_t color)
{
    int total_width = count * 24 + (count - 1) * 4;
    int x = (TFT_WIDTH - total_width) / 2;
    for (int index = 0; index < count; index++) {
        draw_hanzi(x + index * 28, 2, characters[index], color);
    }
}

